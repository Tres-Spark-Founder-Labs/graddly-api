/**
 * F2.4.2 AC1 — how the visit happened.
 *
 * Ofsted distinguishes these. A programme where every "employer engagement"
 * was a phone call reads differently in an inspection from one with regular
 * on-site visits, and a provider needs to be able to show the mix rather than
 * a single undifferentiated count.
 */
export enum EmployerVisitType {
  ON_SITE = 'on_site',
  VIDEO = 'video',
  PHONE = 'phone',
}
